def create_footer():
    has_author = bool(AUTHOR)
    author_line = f"; Generated by {AUTHOR}'s {MOD_NAME} generator :3c"

    has_contact = bool(CONTACT)
    contact_line = f"; If you have any issues with this mod, please contact me at {CONTACT}!"

    has_repo = bool(REPO_URL)
    repo_line = f"; The source code for this mod generator can be found at: {REPO_URL}"

    return dedent(f"""\
    
        {author_line if has_author else ""}
        {contact_line if has_contact else ""}
        {";" if has_repo else ""}
        {repo_line if has_repo else ""}
    """)
